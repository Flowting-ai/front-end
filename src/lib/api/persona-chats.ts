"use client";

import { apiFetch, apiFetchJson } from "./client";
import { personaChatsSchema, personaMessagesSchema, type PersonaFileAttachment } from "./persona-schemas";
import { getQueryClient } from "@/lib/query-client";
import { PERSONA_CHATS_ENDPOINT, PERSONA_CHAT_MESSAGES_ENDPOINT, PERSONA_CHATS_RENAME_ENDPOINT, PERSONA_CHAT_STOP_ENDPOINT, PERSONA_CHAT_DELETE_MESSAGE_ENDPOINT } from "@/lib/config";
import type { Persona } from "./persona-model";

// ── Persona chat history ──────────────────────────────────────────────────────

export type {
  PersonaChatsResponse,
  PersonaFileAttachment,
  GetPersonaMessages,
} from "./persona-schemas";

/** Caller-friendly shape: each backend turn is split into a user message + assistant message. */
export interface PersonaChat {
  id:          string;
  title:       string;
  /** Version (backend persona_id) that produced this chat — null for legacy rows. */
  versionId?:  string | null;
  created_at?: string;
  updated_at?: string;
}

export interface PersonaMessage {
  id:          string;
  role:        "user" | "assistant";
  content:     string;
  created_at?: string;
  /** File attachments returned by the backend (uploaded files with their S3 links). */
  file_attachments?: PersonaFileAttachment[];
}

// Chats are only listable per repo (GET /persona/{repo_id}/chats — there is no
// cross-agent equivalent), so "all my agent chats" is structurally one request
// per agent, and three separate call sites want it: the sidebar's recent-chats
// section, global search, and the highlight index. In-flight dedupe + a short
// TTL so those sites share one request per agent instead of each firing its own
// fan-out. The lists live in React Query under the ["personas"] prefix, so
// bustPersonasCache() (an agent deleted or republished) clears them too, and
// logout drops them. The TTL is deliberately shorter than the personas list's:
// a chat's title is generated by the backend moments after the chat is
// created, and nothing client-side knows when that lands.
const PERSONA_CHATS_CACHE_TTL = 10_000
export const personaChatsQueryKey = (repoId: string) => ['personas', 'chats', repoId] as const

/** Drops the cached chat list for one agent (or all of them). Every chat
 *  mutation below calls this, so a create/rename/delete is never masked by a
 *  cache hit — only changes made outside this tab can be up to 30s stale. */
export function bustPersonaChatsCache(repoId?: string): void {
  getQueryClient().removeQueries({ queryKey: repoId ? personaChatsQueryKey(repoId) : ['personas', 'chats'] });
}

/** GET /persona/{repo_id}/chats */
export function fetchPersonaChats(repoId: string): Promise<PersonaChat[]> {
  return getQueryClient().fetchQuery({
    queryKey: personaChatsQueryKey(repoId),
    queryFn: async () => personaChatsSchema.array().parse(await apiFetchJson<unknown>(PERSONA_CHATS_ENDPOINT(repoId)))
      .map(c => ({ id: c.id, title: c.chat_title, versionId: c.persona_id })),
    staleTime: PERSONA_CHATS_CACHE_TTL,
  });
}

/** A chat with an agent, tagged with the agent that owns it. */
export type AgentChat = PersonaChat & { personaId: string };

/**
 * Every chat across the given agents (one cached request per agent, see
 * above). An agent whose list fails is skipped and counted in `failed`, so a
 * caller can say results are partial instead of silently missing them.
 */
export async function fetchAgentChatsFor(
  personas: readonly { id: string }[],
): Promise<{ chats: AgentChat[]; failed: number }> {
  const lists = await Promise.all(
    personas.map(p =>
      fetchPersonaChats(p.id)
        .then(chats => chats.map(c => ({ ...c, personaId: p.id })))
        .catch(() => null),
    ),
  );
  return {
    chats:  lists.flatMap(list => list ?? []),
    failed: lists.filter(list => list === null).length,
  };
}

/** GET /persona/{repo_id}/chats/{chat_id}/messages — each turn → user + assistant pair. */
export async function fetchPersonaChatMessages(
  repoId: string,
  chatId: string,
): Promise<PersonaMessage[]> {
  const turns = personaMessagesSchema.array().parse(await apiFetchJson<unknown>(
    PERSONA_CHAT_MESSAGES_ENDPOINT(repoId, chatId),
  ));
  const out: PersonaMessage[] = [];
  for (const t of turns) {
    if (t.input)  out.push({
      id: `${t.id}:in`,
      role: "user",
      content: t.input,
      file_attachments: t.file_attachments?.filter(a => a.origin === "uploaded" || a.origin === "user"),
    });
    if (t.output) out.push({
      id: `${t.id}:out`,
      role: "assistant",
      content: t.output,
      file_attachments: t.file_attachments?.filter(a => a.origin === "generated"),
    });
  }
  return out;
}

/** PATCH /persona/{repo_id}/chats/rename */
export async function renamePersonaChat(
  repoId: string,
  chatId: string,
  title: string,
): Promise<void> {
  const res = await apiFetch(PERSONA_CHATS_RENAME_ENDPOINT(repoId), {
    method: "PATCH",
    body:   JSON.stringify({ chat_id: chatId, chat_title: title }),
  });
  if (!res.ok) throw new Error(`Failed to rename chat (status ${res.status})`);
  bustPersonaChatsCache(repoId);
}

/** DELETE /persona/{repo_id}/chats — body: { chat_id }. */
export async function deletePersonaChat(repoId: string, chatId: string): Promise<void> {
  const res = await apiFetch(PERSONA_CHATS_ENDPOINT(repoId), {
    method: "DELETE",
    body:   JSON.stringify({ chat_id: chatId }),
  });
  if (!res.ok) throw new Error(`Failed to delete chat (status ${res.status})`);
  bustPersonaChatsCache(repoId);
}

/** POST /persona/{repo_id}/chats/{chat_id}/stop — cancel an in-flight stream. */
export async function stopPersonaChat(repoId: string, chatId: string): Promise<void> {
  const res = await apiFetch(PERSONA_CHAT_STOP_ENDPOINT(repoId, chatId), { method: "POST" });
  if (!res.ok) throw new Error(`Failed to stop chat (status ${res.status})`);
}

/** DELETE /persona/{repo_id}/chats/{chat_id}/message/{message_id}. */
export async function removePersonaMessage(
  repoId: string,
  chatId: string,
  messageId: string,
): Promise<void> {
  const res = await apiFetch(PERSONA_CHAT_DELETE_MESSAGE_ENDPOINT(repoId, chatId, messageId), {
    method: "DELETE",
  });
  if (!res.ok) throw new Error(`Failed to delete message (status ${res.status})`);
}

