"use client";

import { apiFetch, apiFetchJson } from "./client";
import { personaChatsSchema } from "./persona-schemas";
import { getQueryClient } from "@/lib/query-client";
import { CHATS_ENDPOINT, CHATS_RENAME_ENDPOINT } from "@/lib/config";
import { fetchPersonas } from "./persona-list";
import { listVersions } from "./persona-versions";

// ── Persona chat history ──────────────────────────────────────────────────────
//
// An agent chat is an ordinary chat bound to one agent version: POST
// /chats/create with `persona_id` (a version id, not the repo id) stores it on
// the chat row, and the chat stays bound — a later /chats/{id}/stream without
// `persona_id` still runs as that agent. Sending one moves the chat to that
// version. So everything below is the regular /chats API; only the listing
// needs the agent's version ids to find its chats.

export type {
  PersonaChatsResponse,
} from "./persona-schemas";

/** One agent chat as the sidebar and search list it. */
export interface PersonaChat {
  id:          string;
  title:       string;
  /** Version (backend persona_id) that produced this chat — null for legacy rows. */
  versionId?:  string | null;
  created_at?: string;
  updated_at?: string;
}

// GET /chats carries each chat's persona_id, so one list serves every agent:
// the sidebar's recent-chats section, global search and the highlight index
// all read it through React Query instead of each firing its own request. The
// lists live under the ["personas"] prefix, so bustPersonasCache() (an agent
// deleted or republished) clears them too, and logout drops them. The TTL is
// deliberately short: a chat's title is generated by the backend moments after
// the chat is created, and nothing client-side knows when that lands.
const PERSONA_CHATS_CACHE_TTL = 10_000
const PERSONA_VERSIONS_CACHE_TTL = 60_000
export const personaChatsQueryKey = (repoId: string) => ['personas', 'chats', repoId] as const
const allChatsQueryKey = ['personas', 'chats', '*all'] as const
const chatVersionsQueryKey = (repoId: string) => ['personas', 'chats', '*versions', repoId] as const

/** Drops the cached chat lists. Every chat mutation below calls this, so a
 *  create/rename/delete is never masked by a cache hit — only changes made
 *  outside this tab can be up to 10s stale. */
export function bustPersonaChatsCache(repoId?: string): void {
  const qc = getQueryClient();
  if (!repoId) {
    qc.removeQueries({ queryKey: ['personas', 'chats'] });
    return;
  }
  qc.removeQueries({ queryKey: personaChatsQueryKey(repoId) });
  qc.removeQueries({ queryKey: allChatsQueryKey });
}

function fetchAllChats() {
  return getQueryClient().fetchQuery({
    queryKey: allChatsQueryKey,
    queryFn: async () => personaChatsSchema.array().parse(await apiFetchJson<unknown>(CHATS_ENDPOINT)),
    staleTime: PERSONA_CHATS_CACHE_TTL,
  });
}

/**
 * Every version id a chat with this agent can carry. The full version list is
 * owner-only (GET /persona/{repo}/versions), so for an agent received from
 * someone else it falls back to the live and working versions the agent list
 * already knows.
 */
export function personaChatVersionIds(repoId: string): Promise<string[]> {
  return getQueryClient().fetchQuery({
    queryKey: chatVersionsQueryKey(repoId),
    queryFn: async () => {
      try {
        return (await listVersions(repoId)).map(v => v.id);
      } catch {
        const persona = (await fetchPersonas()).find(p => p.id === repoId);
        return [persona?.activeVersionId, persona?.workingVersionId].filter((id): id is string => !!id);
      }
    },
    staleTime: PERSONA_VERSIONS_CACHE_TTL,
  });
}

/** The agent's chats, newest first: GET /chats filtered to its versions. */
export function fetchPersonaChats(repoId: string): Promise<PersonaChat[]> {
  return getQueryClient().fetchQuery({
    queryKey: personaChatsQueryKey(repoId),
    queryFn: async () => {
      const [chats, versionIds] = await Promise.all([fetchAllChats(), personaChatVersionIds(repoId)]);
      const versions = new Set(versionIds);
      return chats
        .filter(c => c.persona_id != null && versions.has(c.persona_id))
        .map(c => ({ id: c.id, title: c.chat_title, versionId: c.persona_id, created_at: c.created_at, updated_at: c.updated_at }));
    },
    staleTime: PERSONA_CHATS_CACHE_TTL,
  });
}

/** A chat with an agent, tagged with the agent that owns it. */
export type AgentChat = PersonaChat & { personaId: string };

/**
 * Every chat across the given agents (one shared chat list, one cached version
 * lookup per agent). An agent whose lookup fails is skipped and counted in
 * `failed`, so a caller can say results are partial instead of silently
 * missing them.
 */
export async function fetchAgentChatsFor(
  personas: readonly { id: string }[],
): Promise<{ chats: AgentChat[]; failed: number }> {
  const lists = await Promise.all(
    personas.map(p =>
      fetchPersonaChats(p.id)
        .then(chats => chats.map(c => ({ ...c, personaId: p.id })))
        .catch(() => null),
    ),
  );
  return {
    chats:  lists.flatMap(list => list ?? []),
    failed: lists.filter(list => list === null).length,
  };
}

/** PATCH /chats/rename. `repoId` only scopes the cache bust. */
export async function renamePersonaChat(
  repoId: string,
  chatId: string,
  title: string,
): Promise<void> {
  const res = await apiFetch(CHATS_RENAME_ENDPOINT, {
    method: "PATCH",
    body:   JSON.stringify({ chat_id: chatId, chat_title: title }),
  });
  if (!res.ok) throw new Error(`Failed to rename chat (status ${res.status})`);
  bustPersonaChatsCache(repoId);
}

/** DELETE /chats — body: { chat_id }. `repoId` only scopes the cache bust. */
export async function deletePersonaChat(repoId: string, chatId: string): Promise<void> {
  const res = await apiFetch(CHATS_ENDPOINT, {
    method: "DELETE",
    body:   JSON.stringify({ chat_id: chatId }),
  });
  if (!res.ok) throw new Error(`Failed to delete chat (status ${res.status})`);
  bustPersonaChatsCache(repoId);
}
