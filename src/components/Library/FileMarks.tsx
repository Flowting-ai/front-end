'use client'

import React, { useId } from 'react'
import { Badge } from '@/components/Badge'
import { Tooltip } from '@/components/Tooltip'
import { MESSAGES } from '@/lib/library/messages'
import type { LibraryFile } from '@/lib/library/file'

/**
 * The signature pink dot (fixed, so it stays pink in every theme). A dot plus a heavier file name means
 * unread; the dot also carries a label and an "Unread" tooltip, so it is not colour alone.
 */
export function UnreadDot() {
  return (
    <Tooltip content={MESSAGES.unread}>
      <span
        role="img"
        aria-label={MESSAGES.unread}
        style={{ display: 'inline-block', flexShrink: 0, width: 8, height: 8, borderRadius: '50%', background: '#F92064' }}
      />
    </Tooltip>
  )
}

/** Where a Generated file was made, in words: "Generated in Refund questions", "Generated by the Weekly sales report routine". */
export function generatedDetail(file: Pick<LibraryFile, 'source' | 'generatedFrom'>): string {
  const from = file.generatedFrom
  if (from?.kind === 'routine') return MESSAGES.generatedByRoutine(from.label)
  if (from?.kind === 'chat') return MESSAGES.generatedInChat(from.label)
  return MESSAGES.generatedBy
}

/**
 * A soft mint sparkle after the name of a file Souvenir made (a chat output or a routine run output):
 * the prototype's sparkle shape, filled and stroked with the #a6ebcf to #3fb98a gradient.
 */
export function GeneratedMark({ detail, file }: { detail?: string; file?: Pick<LibraryFile, 'source' | 'generatedFrom'> }) {
  const gradientId = useId()
  const label = file ? generatedDetail(file) : detail ? `${MESSAGES.generatedBy}: ${detail}` : MESSAGES.generatedBy
  const paint = `url(#${gradientId})`
  return (
    <Tooltip content={label}>
      <span role="img" aria-label={label} style={{ display: 'inline-flex', flexShrink: 0, lineHeight: 0, cursor: 'default' }}>
        <svg width="14" height="14" viewBox="0 0 24 24" fill={paint} stroke={paint} strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
          <defs>
            <linearGradient id={gradientId} gradientUnits="userSpaceOnUse" x1="3" y1="3" x2="21" y2="21">
              <stop offset="0" stopColor="#a6ebcf" />
              <stop offset="1" stopColor="#3fb98a" />
            </linearGradient>
          </defs>
          <path d="M11.017 2.814a1 1 0 0 1 1.966 0l1.051 5.558a2 2 0 0 0 1.594 1.594l5.558 1.051a1 1 0 0 1 0 1.966l-5.558 1.051a2 2 0 0 0-1.594 1.594l-1.051 5.558a1 1 0 0 1-1.966 0l-1.051-5.558a2 2 0 0 0-1.594-1.594l-5.558-1.051a1 1 0 0 1 0-1.966l5.558-1.051a2 2 0 0 0 1.594-1.594z" />
          <path d="M20 2v4" />
          <path d="M22 4h-4" />
          <circle cx="4" cy="20" r="2" />
        </svg>
      </span>
    </Tooltip>
  )
}

/** Marks a title Souvenir chose, until the owner renames it. */
export function AiGeneratedTag() {
  return <Badge label={MESSAGES.aiGeneratedTitle} color="Green" />
}
